import pytest

from datacleanr.core.jsnumber import js_number_to_string


# Expected values produced by Node.js String(number)
@pytest.mark.parametrize(
    ("value", "expected"),
    [
        (433.0, "433"),
        (433.0, "433"),
        (5837.32, "5837.32"),
        (0.1, "0.1"),
        (-1234.5, "-1234.5"),
        (1e-05, "0.00001"),
        (1e-06, "0.000001"),
        (1e-07, "1e-7"),
        (1.5e-10, "1.5e-10"),
        (1.2345678901234568e20, "123456789012345680000"),
        (1e21, "1e+21"),
        (1e16, "10000000000000000"),
        (1.2345678901234567e19, "12345678901234567000"),
        (0.30000000000000004, "0.30000000000000004"),
        (0.6666666666666666, "0.6666666666666666"),
        (0.3333333333333333, "0.3333333333333333"),
        (100.0, "100"),
        (1e100, "1e+100"),
        (-0.5, "-0.5"),
        (5e-324, "5e-324"),
        (1.7976931348623157e308, "1.7976931348623157e+308"),
        (45678.25, "45678.25"),
        (3e-05, "0.00003"),
    ],
)
def test_matches_javascript(value, expected):
    assert js_number_to_string(value) == expected
